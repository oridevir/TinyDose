-- מחזיר את הכללים שלפני migration-owner-only.sql (כל משתמש מחובר רשאי לערוך).
begin;
drop policy "Owner insert categories" on public.categories;
drop policy "Owner update categories" on public.categories;
drop policy "Owner delete categories" on public.categories;
create policy "Auth insert categories" on public.categories for insert with check (auth.role() = 'authenticated');
create policy "Auth update categories" on public.categories for update using (auth.role() = 'authenticated');
create policy "Auth delete categories" on public.categories for delete using (auth.role() = 'authenticated');
drop policy "Owner insert drugs" on public.drugs;
drop policy "Owner update drugs" on public.drugs;
drop policy "Owner delete drugs" on public.drugs;
create policy "Auth insert drugs" on public.drugs for insert with check ((select auth.role()) = 'authenticated');
create policy "Auth update drugs" on public.drugs for update using ((select auth.role()) = 'authenticated');
create policy "Auth delete drugs" on public.drugs for delete using ((select auth.role()) = 'authenticated');
drop policy "Owner insert indications" on public.indications;
drop policy "Owner update indications" on public.indications;
drop policy "Owner delete indications" on public.indications;
create policy "Auth insert indications" on public.indications for insert with check (auth.role() = 'authenticated');
create policy "Auth update indications" on public.indications for update using (auth.role() = 'authenticated');
create policy "Auth delete indications" on public.indications for delete using (auth.role() = 'authenticated');
drop policy "Owner insert products" on public.products;
drop policy "Owner update products" on public.products;
drop policy "Owner delete products" on public.products;
create policy "Auth insert products" on public.products for insert with check ((select auth.role()) = 'authenticated');
create policy "Auth update products" on public.products for update using ((select auth.role()) = 'authenticated');
create policy "Auth delete products" on public.products for delete using ((select auth.role()) = 'authenticated');
drop policy "Owner insert recommendations" on public.recommendations;
drop policy "Owner update recommendations" on public.recommendations;
drop policy "Owner delete recommendations" on public.recommendations;
create policy "Auth insert recommendations" on public.recommendations for insert with check ((select auth.role()) = 'authenticated');
create policy "Auth update recommendations" on public.recommendations for update using ((select auth.role()) = 'authenticated');
create policy "Auth delete recommendations" on public.recommendations for delete using ((select auth.role()) = 'authenticated');
drop policy "Owner insert medications" on public.medications;
drop policy "Owner update medications" on public.medications;
drop policy "Owner delete medications" on public.medications;
create policy "Auth insert" on public.medications for insert with check (auth.role() = 'authenticated');
create policy "Auth update" on public.medications for update using (auth.role() = 'authenticated');
create policy "Auth delete" on public.medications for delete using (auth.role() = 'authenticated');
drop policy "Read verified or owner recommendations" on public.recommendations;
create policy "Read verified or auth recommendations" on public.recommendations for select using (status = 'verified' or (select auth.role()) = 'authenticated');
commit;
